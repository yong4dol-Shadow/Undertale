  function spawn(id) {
    const d = DB[id];
    if (!d) throw new Error('unknown enemy: ' + id);
    const e = Object.assign({}, d);
    e.id = id;
    e.maxhp = d.hp;
    e.hp = d.hp;
    e.f = {};
    e.sparable = false;
    e.turn = 0;
    return e;
  }

